#!/usr/bin/env python3
"""Render the reviewed glossary into bilingual_book_maker pins."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def load(path: Path) -> list[dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    entries = data.get("entries") if isinstance(data, dict) else data
    if not isinstance(entries, list):
        raise ValueError("glossary JSON must contain an 'entries' list")
    return entries


def accepted(entries: list[dict]) -> list[dict]:
    result = []
    for index, entry in enumerate(entries, 1):
        if not isinstance(entry, dict):
            raise ValueError(f"entry {index} is not an object")
        source = str(entry.get("source", "")).strip()
        target = str(entry.get("target", "")).strip()
        status = entry.get("status", "accepted")
        if not source or not target:
            raise ValueError(f"entry {index} needs non-empty source and target")
        if status not in {"accepted", "confirmed"}:
            continue
        result.append({"source": source, "target": target, "sense": str(entry.get("sense", "")).strip()})
    return result


def render(entries: list[dict]) -> str:
    seen: dict[str, str] = {}
    lines: list[str] = [
        "# Reviewed by the user; one exact pin per line.",
        "# Generated by Yidu. Do not hand-edit during a run.",
    ]
    for entry in entries:
        source, target, sense = entry["source"], entry["target"], entry["sense"]
        old = seen.get(source)
        if old and old != target:
            raise ValueError(
                f"ambiguous glossary source {source!r}: {old!r} vs {target!r}. "
                "Use a longer source phrase or resolve the sense before translating."
            )
        if not old:
            seen[source] = target
            note = f"  # {sense}" if sense else ""
            lines.append(f"{source} -> {target}{note}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    try:
        args.output.write_text(render(accepted(load(args.input))), encoding="utf-8")
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"yidu glossary renderer: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
